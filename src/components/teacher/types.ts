/**
 * Serialisable view models for the teacher evidence views. Built on the server
 * (src/components/teacher/server/evidence.ts) and rendered by EvidencePanel in
 * both the heatmap drawer (client) and the full evidence page (server).
 * Dates are ISO strings so they cross the server→client boundary unchanged.
 */
import type { MasteryLevel } from "@/modules/mastery/types";
import type { MisconceptionStatus } from "@/db/schema";

export interface EvidenceResponse {
  id: string;
  attemptId: string;
  prompt: string;
  patternLabel: string;
  modeLabel: string;
  summative: boolean;
  correct: boolean;
  /** 0..1 */
  score: number;
  independent: boolean;
  /** Plain-language assistance used before answering ("1 hint", "retry after feedback", …). */
  assistance: string[];
  /** The student's answer, as display text (may contain Markdown/maths). */
  studentAnswer: string | null;
  correctAnswer: string | null;
  misconceptionTitle: string | null;
  occurredAt: string;
}

export interface EvidenceAssessmentResult {
  attemptId: string;
  modeLabel: string;
  at: string;
  correct: number;
  total: number;
}

export interface EvidenceMisconception {
  id: string;
  title: string;
  description: string;
  remediation: string;
  status: MisconceptionStatus;
  detectionMethod: "answer_pattern_rule" | "teacher";
  occurrences: number;
  correctSinceLast: number;
  lastObservedAt: string;
}

export interface EvidencePrerequisite {
  id: string;
  name: string;
  level: MasteryLevel;
  /** Below Proficient with mostly incorrect answers. */
  weak: boolean;
}

export interface Recommendation {
  /** One-line headline: what to do next. */
  title: string;
  /** Why, in plain language, from the evidence. */
  reason: string;
  tone: "support" | "gather" | "review" | "on_track";
}

export interface SkillEvidence {
  skillId: string;
  name: string;
  description: string;
  level: MasteryLevel;
  needsReview: boolean;
  reviewReason: string | null;
  hasEvidence: boolean;
  /** Below Proficient but answers so far are mostly correct (too little evidence to call). */
  mostlyCorrect: boolean;
  /** Generated by the mastery engine from the same counts shown here. */
  summary: string | null;
  nextLevel: MasteryLevel | null;
  /** Requirements still unmet for nextLevel. */
  unmet: string[];
  counts: {
    attempts: number;
    correct: number;
    independentAttempts: number;
    independentCorrect: number;
    assistedAttempts: number;
    uniqueQuestions: number;
    uniqueQuestionsCorrect: number;
    distinctPatternsCorrect: number;
    summativeIndependentCorrect: number;
    distinctSittings: number;
  };
  patterns: { label: string; attempts: number; independentAttempts: number; independentCorrect: number }[];
  weakestPattern: string | null;
  responses: EvidenceResponse[];
  assessments: EvidenceAssessmentResult[];
  misconceptions: EvidenceMisconception[];
  /** Level changes only (consecutive duplicates removed), oldest first. */
  history: { at: string; level: MasteryLevel }[];
  prerequisites: EvidencePrerequisite[];
  lastDemonstratedAt: string | null;
  recommendation: Recommendation;
}

export interface CellEvidence {
  classId: string;
  student: { id: string; name: string };
  column: { id: string; kind: "objective" | "skill"; label: string; description: string };
  level: MasteryLevel;
  needsReview: boolean;
  skillsWithEvidence: number;
  totalSkills: number;
  /** Plain-language explanation of the column level. */
  explanation: string;
  skills: SkillEvidence[];
  recommendation: Recommendation;
  /** Skills worth targeting with practice (weak or untested), for the prefilled assignment link. */
  practiceSkillIds: string[];
}

export type CellEvidenceResult = { ok: true; evidence: CellEvidence } | { ok: false; error: string };
